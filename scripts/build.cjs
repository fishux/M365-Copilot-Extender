// Prebuild one self-contained script per runtime context. No shared script must
// execute first, and the helpers live in a private lexical scope, not on window.
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const checking = process.argv.includes('--check');
const read = name => fs.readFileSync(path.join(root, 'src', name), 'utf8');
const localize = source => source
  .replaceAll('globalThis.M365ExtenderCore', 'shared.core')
  .replaceAll('globalThis.M365ExtenderPanel', 'shared.panel');
for (const name of ['page-hook.js', 'content.js', 'popup.js']) {
  const generated = `/* Generated by scripts/build.cjs. Edit src/ files, then run npm run build. */\n(() => {\n  const shared = {};\n${localize(read('core.js'))}\n${localize(read(name))}\n})();\n`;
  const target = path.join(root, 'extension', name);
  if (checking) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== generated) {
      throw new Error(`${name} is out of date. Run npm run build.`);
    }
  } else fs.writeFileSync(target, generated);
}
console.log(checking ? 'Runtime bundles match their sources.' : 'Built 3 self-contained runtime scripts.');
