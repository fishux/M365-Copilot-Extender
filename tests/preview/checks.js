const pause = ms => new Promise(resolve => setTimeout(resolve, ms));
document.getElementById('checks').addEventListener('click', async () => {
  const result = document.getElementById('results'); const passed = [];
  const check = (condition, name) => { if (!condition) throw new Error(name); passed.push(name); };
  result.textContent = 'Running…';
  try {
    const copilot = document.getElementById('copilot').contentWindow;
    const popup = document.getElementById('popup').contentWindow;
    const popupRoot = popup.document.getElementById('panel').shadowRoot;
    const choose = (root, value) => { const select = root.querySelector('select'); select.value = value; select.dispatchEvent(new Event('change', { bubbles: true })); };
    await fixtureStore.set({ selectedTone: 'Gpt_61_Sol_Reasoning' }); await pause(1600);
    check(!copilot.document.querySelector('m365-copilot-extender'), 'No extension UI injected into Copilot');
    check(!popupRoot.querySelector('input, .collapse, .settings'), 'No page visibility or collapse controls');
    check(popupRoot.querySelector('#model').options.length === 6, 'Six model options');
    choose(popupRoot, 'Gpt_6_Sol_Reasoning'); await pause(1600);
    check(fixtureStore.data.selectedTone === 'Gpt_6_Sol_Reasoning', 'Popup selection is saved');
    check(popupRoot.querySelector('.usage').hidden, 'No invented GPT-6 Sol quota');
    copilot.simulateReply(); await pause(1600);
    check(copilot.document.getElementById('wire').textContent.includes('Gpt_6_Sol_Reasoning'), 'Outgoing request is overridden');
    choose(popupRoot, 'Gpt_61_Sol_Reasoning'); await pause(1600);
    check(fixtureStore.data.selectedTone === 'Gpt_61_Sol_Reasoning', 'Next popup selection is saved');
    copilot.simulateReply(0, 0); await pause(1600);
    check(popupRoot.querySelector('.daily').textContent === '0', 'Zero quota stays visible');
    check(popupRoot.querySelector('.status-text').textContent.includes('usage limit'), 'Quota refusal is surfaced');
    copilot.simulateReply(30, 50, true); await pause(1600);
    check(popupRoot.querySelector('.daily').textContent === '0' && !popupRoot.querySelector('.counts').hidden, 'Missing quota preserves last reported allowance');
    check(popupRoot.querySelector('.capacity-count').textContent === '4 / 600 messages', 'Conversation capacity is visible');
    check(popupRoot.querySelector('.capacity-track').getAttribute('aria-valuemax') === '600', 'Capacity meter uses the server limit');
    copilot.simulateConversation(600, 600, new Date(Date.now() - 1000).toISOString()); await pause(1600);
    check(popupRoot.querySelector('.capacity-count').classList.contains('near-limit'), 'Full conversation is highlighted');
    check(popupRoot.querySelector('.expiry-value').textContent.endsWith('Passed'), 'Passed expiry is explicit');
    copilot.simulateConversation(undefined, undefined, 'invalid'); await pause(1600);
    check(!popupRoot.querySelector('.capacity-track').hidden && popupRoot.querySelector('.capacity-count').textContent === '600 / 600 messages', 'Missing capacity preserves last reading');
    check(popupRoot.querySelector('.expiry-value').textContent.endsWith('Passed'), 'Invalid expiry preserves last valid reading');
    copilot.simulateReply(32, 58); await pause(1600);
    check(popupRoot.querySelector('.daily').textContent === '32', 'Popup reads active-tab quota');
    copilot.simulateReply(18, 40); await pause(1600);
    check(popupRoot.querySelector('.daily').classList.contains('low') && fixtureToolbar.remaining === 18, 'Allowance of 20 or less is highlighted orange');
    copilot.simulateReply(9, 40); await pause(1600);
    check(popupRoot.querySelector('.daily').classList.contains('critical') && fixtureToolbar.remaining === 9, 'Allowance of 10 or less is highlighted red');
    const conversationSelect = popupRoot.querySelector('#conversation-model');
    check(!conversationSelect.disabled && conversationSelect.value === '', 'Conversation selector is available after a send');
    choose(popupRoot, 'Gpt_5_5_Reasoning'); conversationSelect.value = 'Gpt_6_Reasoning';
    conversationSelect.dispatchEvent(new Event('change', { bubbles: true })); await pause(1600);
    check(Object.values(fixtureStore.data.conversationTones || {}).some(entry => entry.tone === 'Gpt_6_Reasoning'), 'Conversation model is saved under a hashed key');
    check(!JSON.stringify(fixtureStore.data).includes('0f0e0d0c'), 'Raw conversation ID is not stored');
    copilot.simulateReply(32, 58); await pause(1600);
    check(copilot.document.getElementById('wire').textContent.includes('Gpt_6_Reasoning'), 'Conversation model overrides the default');
    check(fixtureToolbar.tone === 'Gpt_6_Reasoning', 'Toolbar reports the conversation model');
    conversationSelect.value = ''; conversationSelect.dispatchEvent(new Event('change', { bubbles: true })); await pause(1600);
    copilot.simulateReply(32, 58); await pause(1600);
    check(copilot.document.getElementById('wire').textContent.includes('Gpt_5_5_Reasoning'), 'Clearing the conversation model restores the default');
    choose(popupRoot, 'Gpt_61_Sol_Reasoning'); await pause(1600);
    copilot.simulateReply(32, 58); await pause(1600);
    check(popupRoot.querySelector('.capacity-count').textContent === '4 / 600 messages', 'Popup reads active-tab conversation capacity');
    check(popupRoot.querySelector('.expiry-value').getAttribute('datetime') !== null, 'Popup receives server expiry');
    check(popupRoot.querySelector('.expiry-value').title.includes('not a guaranteed data deletion date'), 'Exact expiry explains its meaning');
    result.textContent = passed.length + ' UI checks passed · simulated transport'; result.dataset.status = 'passed';
  } catch (error) { result.textContent = 'FAILED: ' + error.message; result.dataset.status = 'failed'; }
});
